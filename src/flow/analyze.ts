/**
 * Offline analyzer (spec §7): drafts flows and ANALYSIS.md from a validated run.json and the
 * manifest. Zero network: this module imports no transport and performs no DNS lookups.
 * It encodes only observed, legitimate behaviour and leaves "is this public?" to the owner.
 */
import type { Manifest } from "../config.js";
import { ScopeGate } from "../scope.js";
import type { ObservedRequest, RunResult } from "../types.js";
import { FLOW_ID } from "./parse.js";

const RISKY = /^(logout|log-out|signout|sign-out|delete|remove|destroy|reset|revoke|cancel|unsubscribe|approve|confirm)$/i;
const ID_LIKE = /^(\d+|[0-9a-f]{8,}|[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})$/i;
const MAX_GENERATED_STEPS = 20;

export interface AnalyzeOutput {
  /** file name → content */
  files: Map<string, string>;
  skippedExisting: string[];
}

interface Endpoint {
  origin: string;
  path: string;
  byActor: Map<string, ObservedRequest>;
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

function groupId(prefix: string, path: string): string {
  const segs = path.split("/").filter(Boolean).slice(0, 2).map(slug).filter(Boolean);
  return `${prefix}-${segs.length ? segs.join("-") : "root"}`.slice(0, 60).replace(/-+$/, "");
}

const kind = (q: ObservedRequest) => {
  const ct = q.contract?.contentType ?? "";
  if (q.status !== undefined && q.status >= 300 && q.status < 400) return "redirect";
  if (ct === "text/html") return "page";
  return "api";
};

function stepBlock(title: string, step: Record<string, unknown>): string {
  return [`## ${step.id} — ${title}`, "", "```navsentry-step", JSON.stringify(step, null, 2), "```", ""].join("\n");
}

function flowFile(id: string, title: string, story: string, actors: string[], steps: { title: string; step: Record<string, unknown> }[], run: RunResult, origin: string, multiOrigin: boolean): string {
  const header = {
    flow: "1", id, title, story, level: "auto", ...(multiOrigin ? { origin } : {}), actors: [...new Set(["anonymous", ...actors])].sort(),
    review: { status: "draft" }, provenance: { kind: "analyzer", from_run: run.runId, created_at: run.finishedAt },
  };
  return [`# ${title}`, "", "Draft generated by `navsentry flow analyze` from observed, legitimate responses. Review every step before approving.", "",
    "```navsentry-flow", JSON.stringify(header, null, 2), "```", "", ...steps.map((s, i) => stepBlock(s.title, { ...s.step, id: `S${i + 1}` }))].join("\n");
}

export function analyzeRun(run: RunResult, m: Manifest, existingIds: Set<string>, lang: "en" | "th" = "en"): AnalyzeOutput {
  const gate = new ScopeGate(m);
  const actorsKnown = new Set(Object.keys(m.actors));
  const files = new Map<string, string>();
  const skippedExisting: string[] = [];
  const gaps: string[] = [];
  const decisions: string[] = [];
  const notes: string[] = [];
  const endpoints = new Map<string, Endpoint>();

  for (const q of run.requests) {
    if (q.method !== "GET" || q.requestHeaders["origin"] || q.flow) continue;
    if (q.error || q.status === undefined) continue;
    let u: URL;
    try {
      u = new URL(q.url);
    } catch {
      continue;
    }
    if (u.search) continue;
    if (!q.redaction.safe) { gaps.push(`${u.pathname} (${q.actor}): evidence withheld (${q.redaction.kinds.join(", ")}); not encoded`); continue; }
    if (!actorsKnown.has(q.actor)) { notes.push(`${u.pathname}: actor ${q.actor} is not in the current manifest; skipped`); continue; }
    const key = `${u.origin}${u.pathname}`;
    const ep = endpoints.get(key) ?? { origin: u.origin, path: u.pathname, byActor: new Map() };
    if (!ep.byActor.has(q.actor)) ep.byActor.set(q.actor, q);
    endpoints.set(key, ep);
  }

  const multiOrigin = m.targets.origins.length > 1;
  const groups = new Map<string, { origin: string; prefix: "int" | "e2e"; steps: { title: string; step: Record<string, unknown> }[]; actors: Set<string> }>();
  const add = (prefix: "int" | "e2e", ep: Endpoint, title: string, step: Record<string, unknown>) => {
    const gid = `${groupId(prefix, ep.path)}${multiOrigin ? `-${slug(new URL(ep.origin).host)}` : ""}`;
    const g = groups.get(gid) ?? { origin: ep.origin, prefix, steps: [], actors: new Set<string>() };
    g.steps.push({ title, step });
    g.actors.add(step.actor as string);
    groups.set(gid, g);
  };
  const inventory: string[] = [];

  for (const ep of [...endpoints.values()].sort((a, b) => (a.origin + a.path).localeCompare(b.origin + b.path))) {
    const entries = [...ep.byActor.entries()].sort(([a], [b]) => a.localeCompare(b));
    inventory.push(`| \`${ep.path}\` | ${entries.map(([a, q]) => `${a}: ${q.status} ${q.contract?.contentType || "—"}`).join("<br>")} |`);
    const segs = ep.path.split("/");
    if (segs.some((s) => RISKY.test(s))) { notes.push(`${ep.path}: path suggests a side effect on GET; not encoded`); continue; }
    if (!gate.checkRequest(`${ep.origin}${ep.path}`, "GET").allowed) { notes.push(`${ep.path}: now out of scope for this manifest; not encoded`); continue; }
    if (segs.some((s) => ID_LIKE.test(s))) decisions.push(`\`${ep.path}\` contains a segment that looks like an object id. Consider a variable (\`extract\` from a list step) and an IDOR pair: owner \`allowed\` + other actor \`denied\` with \`object_owner\` (NSC-AC-003).`);
    const ok = entries.filter(([, q]) => q.status! >= 200 && q.status! < 300);
    const denied = entries.filter(([, q]) => q.status === 401 || q.status === 403);
    for (const [a, q] of entries) if (q.status! >= 500) notes.push(`${ep.path} (${a}): status ${q.status} observed; server errors are not encoded as expectations — fix or report them`);
    const k = ok[0] ? kind(ok[0][1]) : entries[0] ? kind(entries[0][1]) : "api";
    if (k === "redirect") {
      for (const [a, q] of entries) {
        const loc = q.responseHeaders?.["location"]?.[0];
        if (!loc) continue;
        let target: URL;
        try {
          target = new URL(loc, `${ep.origin}${ep.path}`);
        } catch {
          continue;
        }
        if (target.origin !== ep.origin || target.search || !gate.checkRequest(target.toString(), "GET").allowed) { notes.push(`${ep.path} (${a}): redirects outside the scope; not encoded`); continue; }
        add("e2e", ep, `${a} is redirected from ${ep.path}`, { id: "S0", action: "navigate", actor: a, request: { method: "GET", path: ep.path }, expect: { status: [q.status], redirect_to: target.pathname } });
      }
      continue;
    }
    if (!ok.length) continue;
    const anonOk = ok.find(([a]) => a === "anonymous");
    const authOk = ok.find(([a]) => a !== "anonymous");
    if (anonOk && authOk && anonOk[1].contract?.contentType === authOk[1].contract?.contentType && (anonOk[1].contract?.jsonShapeHash ?? "") === (authOk[1].contract?.jsonShapeHash ?? "")) {
      const tpl = (access: "allowed" | "denied") => JSON.stringify({ id: "S?", action: k === "page" ? "navigate" : "http", actor: "anonymous", request: { method: "GET", path: ep.path, ...(k === "page" ? {} : { accept: "json" }) }, expect: { access } });
      decisions.push(`Is \`${ep.path}\` public? anonymous and ${authOk[0]} received the same ${anonOk[1].status} contract (candidate NSC-AC-002, not a finding). Public → \`${tpl("allowed")}\` · Protected → \`${tpl("denied")}\` (keep ${authOk[0]} as positive control).`);
    }
    for (const [a, q] of ok) {
      if (anonOk && authOk && a === "anonymous") continue; // left to the owner's decision above
      const c = q.contract!;
      const expect: Record<string, unknown> = { status: [q.status], ...(c.contentType ? { content_type: c.contentType } : {}), ...(c.jsonShapeHash ? { shape: c.jsonShapeHash } : {}) };
      if (denied.length) expect.access = "allowed";
      if (k === "page") add("e2e", ep, `${a} opens ${ep.path}`, { id: "S0", action: "navigate", actor: a, request: { method: "GET", path: ep.path }, expect });
      else add("int", ep, `${a} reads ${ep.path}`, { id: "S0", action: "http", actor: a, request: { method: "GET", path: ep.path, accept: c.jsonShapeHash ? "json" : "any" }, expect });
    }
    if (denied.length) {
      for (const [a, q] of denied) {
        add(k === "page" ? "e2e" : "int", ep, `${a} must be denied ${ep.path}`, { id: "S0", action: k === "page" ? "navigate" : "http", actor: a, request: { method: "GET", path: ep.path, ...(k === "page" ? {} : { accept: "json" }) }, expect: { access: "denied", deny_status: [q.status] } });
      }
    }
    if (entries.every(([a]) => a === "anonymous") && actorsKnown.size > 1) notes.push(`${ep.path}: observed only for anonymous; add authenticated actors to compare access`);
  }

  for (const [gid, g] of [...groups.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    for (let part = 0; part * MAX_GENERATED_STEPS < g.steps.length; part++) {
      const id = part ? `${gid}-${part + 1}` : gid;
      if (!FLOW_ID.test(id)) continue;
      if (existingIds.has(id)) { skippedExisting.push(id); continue; }
      const steps = g.steps.slice(part * MAX_GENERATED_STEPS, (part + 1) * MAX_GENERATED_STEPS);
      const title = g.prefix === "int" ? `API: ${id.replace(/^int-/, "")}` : `Pages: ${id.replace(/^e2e-/, "")}`;
      const story = g.prefix === "int" ? "Observed API responses keep their status, media type and JSON shape for each actor." : "Observed pages load (or redirect) for each actor as they did in the source run.";
      files.set(`${id}.flow.md`, flowFile(id, title, story, [...g.actors], steps, run, g.origin, multiOrigin));
    }
  }

  const covered = new Set(run.coverage.filter((c) => c.status !== "NOT_TESTED").map((c) => c.ruleId));
  const gapHints: string[] = [];
  for (const [id, hint] of [["NSC-AC-002", "flows with `access: denied` for anonymous + a positive control"], ["NSC-AC-003", "flows with `object_owner` + `access: denied` for another actor"], ["NSC-AC-007", "flows with `access: denied` for a lower role + a privileged positive control"], ["NSC-INJ-004", "browser transport (M1b) / M2"], ["NSC-AC-006", "safe-validate mutations (M2)"]] as const) {
    if (!covered.has(id)) gapHints.push(`| ${id} | ${hint} |`);
  }
  const th = lang === "th";
  const md = [
    `# ${th ? "ผลการวิเคราะห์ NavSentry (flow analyze)" : "NavSentry flow analysis"}`, "",
    `- Source run: \`${run.runId}\` (${run.finishedAt}) · project ${run.project} · environment ${run.environment}`,
    `- ${th ? "สร้างโฟลว์ร่าง" : "Draft flows written"}: ${files.size} · ${th ? "มีอยู่แล้ว (ไม่แก้ไข)" : "existing, not modified"}: ${skippedExisting.length ? skippedExisting.join(", ") : "none"}`,
    "", `> ${th ? "โฟลว์ทั้งหมดเป็น draft ต้องให้เจ้าของระบบตรวจและอนุมัติด้วย `navsentry flow approve` ก่อนใช้เป็นหลักฐาน" : "All flows are drafts. The owner reviews them and approves with `navsentry flow approve` before they count as evidence."}`, "",
    `## ${th ? "รายการ endpoint ที่พบ" : "Endpoint inventory"}`, "", "| Path | Actor: status media type |", "|---|---|", ...(inventory.length ? inventory : ["| — | — |"]), "",
    `## ${th ? "เรื่องที่เจ้าของต้องตัดสินใจ" : "Decisions needed"}`, "", ...(decisions.length ? decisions.map((d) => `- ${d}`) : ["- none"]), "",
    `## ${th ? "ข้อสังเกต (ไม่ได้บันทึกเป็นความคาดหวัง)" : "Notes (not encoded as expectations)"}`, "", ...(notes.length || gaps.length ? [...notes, ...gaps].map((n) => `- ${n}`) : ["- none"]), "",
    `## ${th ? "ช่องว่างความครอบคลุม" : "Coverage gaps"}`, "", "| Case | What would cover it |", "|---|---|", ...(gapHints.length ? gapHints : ["| — | — |"]), "",
    th ? "UI journey ต้องใช้ browser transport (M1b) · mutation ต้องใช้ safe-validate (M2)" : "UI journeys need the browser transport (M1b); mutations need safe-validate (M2).", "",
  ].join("\n");
  files.set("ANALYSIS.md", md);
  return { files, skippedExisting };
}
