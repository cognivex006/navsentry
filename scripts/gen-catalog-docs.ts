function matrixMd(): string {
  const out: string[] = [];
  out.push("<!-- GENERATED by scripts/gen-catalog-docs.ts from src/catalog.ts — do not edit by hand. -->", "", "# ISSUE / CVE Matrix", "");
  out.push("Matrix นี้ใช้ติดตามว่าแต่ละ Case ID เกิดขึ้นบ่อยแค่ไหน ใช้เพิ่ม Case ใหม่ และใช้ Upgrade Skill/Rule ในอนาคต แหล่งข้อมูลถูกทำให้เป็นนิรนาม (SRC-A…SRC-F) เพราะ repository เป็น public", "");
  out.push("## 1. ID scheme", "", "- Case: `NSC-<CATEGORY>-<NNN>` — ถาวร ห้าม renumber/reuse; เคสที่เลิกใช้ให้คง ID และทำเครื่องหมาย retired", "- Finding fingerprint: `sha256(caseId + method + url-without-query)[0..24]` — ใช้นับการเกิดซ้ำข้าม run", "- Report entries: `ISSUE-<caseId>-<seq>`, `FIX-<caseId>-<seq>`, `QA-<caseId>-<seq>`; prompt/plan issues ใช้ `PRM-<CAT>-<NNN>`", ...Object.entries(RESERVED_IDS).map(([id, why]) => `- Reserved (do not reuse): \`${id}\` — ${why}`), "");
  out.push("## 2. Sources (anonymized)", "", "| Source | Description |", "|---|---|", ...Object.entries(SOURCES).map(([k, v]) => `| ${k} | ${v} |`), "");
  out.push("## 3. Categories", "", "| Code | Category | Cases | auto | Source instances |", "|---|---|---|---|---|");
  for (const [code, name] of Object.entries(CATEGORIES)) {
    const cs = CASES.filter((c) => c.category === code);
    out.push(`| ${code} | ${name} | ${cs.length} | ${cs.filter((c) => c.automation === "auto").length} | ${cs.reduce((a, c) => a + total(c), 0)} |`);
  }
  out.push(`| **Total** | | **${CASES.length}** | **${CASES.filter((c) => c.automation === "auto").length}** | **${CASES.reduce((a, c) => a + total(c), 0)}** |`, "");
  out.push("## 4. Case matrix", "", "| ID | Title | Sev | Priority | Automation | OWASP 2025 | OWASP 2021 | CWE | WSTG | ASVS 5.0 | Sources ×instances |", "|---|---|---|---|---|---|---|---|---|---|---|");
  for (const c of CASES) {
    const short = (xs: string[]) => xs.map((x) => x.split(" ")[0]).join(", ") || "—";
    out.push(`| [${c.id}](cases/CASE-CATALOG.md#${anchor(c.id)}) | ${esc(c.titleEn)} | ${c.severity} | ${c.priority} | ${c.automation} | ${short(c.owasp2025)} | ${short(c.owasp2021)} | ${c.cwe.join(", ") || "—"} | ${c.wstg.join(", ") || "—"} | ${short(c.asvs5Chapter)} | ${c.sources.length ? [...new Set(c.sources.map((s) => s.src))].map((src) => `${src}×${c.sources.filter((s) => s.src === src).reduce((a, s) => a + s.count, 0)}`).join(" ") : "—"} |`);
  }
  out.push("", "## 5. CVE matrix", "", "| CVE | Summary | Case | Sources |", "|---|---|---|---|");
  for (const c of CASES) for (const cve of c.cve ?? []) out.push(`| ${cve} | ${CVE_INFO[cve] ?? "see NVD"} | ${c.id} | ${[...new Set(c.sources.map((s) => s.src))].join(", ")} |`);
  out.push("", "> CVE rows describe what the source reports flagged. They are not claims that any current system is vulnerable; re-verify against the exact deployed version.", "");
  out.push("## 6. CWE index", "", "| CWE | Cases |", "|---|---|");
  const cwe = new Map<string, string[]>();
  for (const c of CASES) for (const w of c.cwe) cwe.set(w, [...(cwe.get(w) ?? []), c.id]);
  for (const [w, ids] of [...cwe].sort((a, b) => Number(a[0].slice(4)) - Number(b[0].slice(4)))) out.push(`| ${w} | ${ids.join(", ")} |`);
  out.push("", "## 7. OWASP Top 10:2025 coverage", "", "| OWASP 2025 | Cases | auto in v0.1 |", "|---|---|---|");
  const ow = new Map<string, CaseDef[]>();
  for (const c of CASES) for (const o of c.owasp2025) ow.set(o, [...(ow.get(o) ?? []), c]);
  for (const [o, cs] of [...ow].sort()) out.push(`| ${o} | ${cs.map((c) => c.id).join(", ")} | ${cs.filter((c) => c.automation === "auto").length}/${cs.length} |`);
  out.push("", "## 8. Occurrence log (append-only)", "", "เพิ่มแถวใหม่ทุกครั้งที่พบเคสในโครงการใด ๆ (ใช้ชื่อรหัสโครงการ ห้ามใส่ชื่อลูกค้า/host/IP) เพื่อดูแนวโน้มการเกิดซ้ำ", "", "| Date | Case ID | Project code | Source | Instances | Status | Note |", "|---|---|---|---|---|---|---|");
  for (const c of CASES) for (const s of c.sources) out.push(`| ${s.src === "SRC-A" ? "2022" : s.src === "SRC-E" ? "2024" : "2023"} | ${c.id} | ${s.src} | ${s.src} | ${s.count} | ${s.status ?? "Open (as reported)"} | ${esc(s.label)} |`);
  out.push("", "## 9. Adding a case / upgrading a skill", "", "1. Search this matrix for an existing CWE/OWASP match; reuse the case if the root cause is the same (add an occurrence row instead).", "2. Otherwise add a `CaseDef` to `src/catalog.ts` with the next free number in its category — fill FACT, EVIDENCE, ACCEPTANCE, webRecheck, fix, regressionGuard and verified mappings.", "3. If it can be checked passively and deterministically, implement the check in `src/checks/`, add vulnerable + secure fixture routes and tests.", "4. `npm run docs:catalog` then `npm run gate`; update CHANGELOG.md.", "5. Never put customer names, hosts, IPs or source paths in the catalog (a test enforces this).", "");
  return out.join("\n");
}

const files: [string, string][] = [
  [join(ROOT, "docs", "cases", "CASE-CATALOG.md"), catalogMd()],
  [join(ROOT, "docs", "ISSUE-CVE-MATRIX.md"), matrixMd()],
];
const check = process.argv.includes("--check");
let stale = 0;
for (const [p, content] of files) {
  if (check) {
    let cur = "";
    try { cur = readFileSync(p, "utf8"); } catch { /* missing */ }
    if (cur !== content) { stale++; console.error(`stale: ${p}`); }
  } else {
    writeFileSync(p, content);
    console.log(`wrote ${p}`);
  }
}
process.exitCode = stale ? 1 : 0;
