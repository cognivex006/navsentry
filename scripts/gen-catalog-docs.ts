/**
 * Generates docs/cases/CASE-CATALOG.md and docs/ISSUE-CVE-MATRIX.md from src/catalog.ts.
 * `--check` exits 1 when the committed files are stale (used by the local gate).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CASES, CATEGORIES, RESERVED_IDS, SOURCES, type CaseDef } from "../src/catalog.js";

const ROOT = process.cwd();
const PRIORITY_TH = { IMMEDIATE: "🔴 ต้องแก้ทันที (IMMEDIATE)", PLANNED: "🟡 รอได้ / วางแผนแก้ (PLANNED)", CAUTION: "🟠 แก้แล้วอาจกระทบผู้ใช้จริง ต้องระวัง (CAUTION)" } as const;
const AUTO_TH: Record<string, string> = {
  auto: "auto — NavSentry ตรวจอัตโนมัติได้ใน v0.1 (observe)",
  "planned-auto": "planned-auto — วางแผนให้ตรวจอัตโนมัติ",
  assisted: "assisted — NavSentry เก็บหลักฐาน, คน/Agent ยืนยัน",
  "manual-active": "manual-active — ต้องใช้ payload เชิงรุก ห้ามรันอัตโนมัติ ต้องมีอนุญาตเฉพาะ",
  "sast-only": "sast-only — ปัญหาระดับซอร์สโค้ด ใช้ SAST/DevSift ตรวจ",
  infra: "infra — ระดับเครือข่าย/โฮสต์ อยู่นอกขอบเขต Web",
};
const esc = (s: string) => s.replace(/\|/g, "\\|");
const anchor = (id: string) => id.toLowerCase();
const total = (c: CaseDef) => c.sources.reduce((a, s) => a + s.count, 0);

function verifyPrompt(c: CaseDef): string {
  return `[NavSentry ${c.id} — VERIFY / ตรวจสอบ]
Role: security verification agent. Target: <ORIGIN> (environment <ENV>) — only if listed in an
authorized NavSentry manifest. Read-only: do not change code, config or data.
Goal: confirm or refute "${c.titleEn}" (${c.titleTh}).

FACT to test:
${c.fact}

Collect EVIDENCE (redact tokens, cookies, PII, internal IPs BEFORE writing anything):
${c.evidence.map((e) => `- ${e}`).join("\n")}

Method:
1. navsentry validate --config <MANIFEST>  then  navsentry test --config <MANIFEST> --out runs/before
2. Read runs/before/run.json coverage row "${c.id}" and any finding with ruleId "${c.id}".
${c.automation === "auto" ? "3. Confirm in a real browser/DevTools:" : `3. This case is "${c.automation}" — NavSentry alone cannot conclude it. Gather the evidence above manually:`}
${c.webRecheck.map((w) => `   - ${w}`).join("\n")}
4. Decide exactly one status: PASS | FAIL | INCONCLUSIVE | NOT_TESTED | ERROR, with a reason.
   Missing evidence is never PASS. Pattern-only evidence stays SUSPECTED until a human confirms.
${c.caveats?.length ? `\nKnown caveats / false positives:\n${c.caveats.map((x) => `- ${x}`).join("\n")}\n` : ""}
Output: an ISSUE entry (template docs/reports/templates/ISSUE.md) with ID ${c.id}, status,
fingerprint(s), evidence list and this checklist:
- [ ] Target is in the authorized manifest scope
- [ ] NavSentry run.json attached (path) and coverage row quoted
- [ ] Evidence redacted (no secret/PII values)
- [ ] Status + reason recorded; priority = ${c.priority}`;
}

function fixPrompt(c: CaseDef): string {
  return `[NavSentry ${c.id} — FIX / แก้ไข]
Role: remediation agent in the application repository. Follow that repository's own
AGENTS.md/CONTRIBUTING rules. Change only what ${c.id} needs; no unrelated refactors.

Problem (FACT): ${c.fact}
Required change: ${c.fix}

DO NOT BREAK LEGITIMATE CALLERS:
${c.regressionGuard}

Steps:
1. Keep the BEFORE run (runs/before/run.json) from the VERIFY step.
2. Implement the change (configuration first, code only if needed) and add/adjust an automated test.
3. Deploy to the authorized staging environment.
4. navsentry test --config <MANIFEST> --out runs/after
5. navsentry compare --before runs/before/run.json --after runs/after/run.json
   Required: ${c.id} in "Fixed" AND no unexplained "Legitimate-response contract drift".

ACCEPTANCE CRITERIA:
${c.acceptance.map((a) => `- [ ] ${a}`).join("\n")}
- [ ] compare verdict IMPROVED_NO_DRIFT (or every drift row approved by the owner in writing)
- [ ] Changed files + commit recorded in a FIX entry (template docs/reports/templates/FIX.md)`;
}

function recheckPrompt(c: CaseDef): string {
  return `[NavSentry ${c.id} — RECHECK / ตรวจซ้ำบนหน้าเว็บจริง]
Role: independent QA agent (not the agent that wrote the fix). Read-only.
1. Re-run: navsentry test --config <MANIFEST> --out runs/recheck ; coverage "${c.id}" must be PASS
   (or a documented, owner-approved DISMISSED/Exception).
2. On the real web page / endpoint:
${c.webRecheck.map((w) => `   - [ ] ${w}`).join("\n")}
3. Regression: main user flows still work and compare shows no unexplained contract drift.
4. Verdict QA-PASS or QA-FAIL. On QA-FAIL you MUST write improvement criteria
   (template docs/reports/templates/QA.md): failed acceptance item, expected vs observed (redacted),
   most likely cause, next concrete action, owner. "Failed" without a reason is not accepted.`;
}

function catalogMd(): string {
  const out: string[] = [];
  out.push("<!-- GENERATED by scripts/gen-catalog-docs.ts from src/catalog.ts — do not edit by hand. -->", "", "# NavSentry Case Catalog (แคตตาล็อกเคส)", "");
  out.push("แต่ละเคสมี ID ถาวร `NSC-<หมวด>-<เลข>` ข้อเท็จจริง (FACT) หลักฐานที่ต้องเก็บ (EVIDENCE) เกณฑ์ยอมรับ (ACCEPTANCE CRITERIA) ขั้นตอนตรวจซ้ำบนหน้าเว็บจริง ข้อควรระวังต่อผู้ใช้จริง และ Prompt 3 แบบ (Verify / Fix / Recheck) ที่คัดลอกไปสั่ง Agent ได้ทันที", "", "แทนค่า `<ORIGIN>`, `<ENV>`, `<MANIFEST>` ก่อนใช้งาน · ตาราง ID/CWE/CVE ดูที่ [ISSUE-CVE-MATRIX.md](../ISSUE-CVE-MATRIX.md)", "");
  out.push("## สารบัญตามหมวด", "");
  for (const [code, name] of Object.entries(CATEGORIES)) {
    const cs = CASES.filter((c) => c.category === code);
    out.push(`- **${code}** ${name}: ${cs.map((c) => `[${c.id}](#${anchor(c.id)})`).join(", ")}`);
  }
  out.push("");
  for (const [code, name] of Object.entries(CATEGORIES)) {
    out.push(`## ${code} — ${name}`, "");
    for (const c of CASES.filter((x) => x.category === code)) {
      out.push(`<a id="${anchor(c.id)}"></a>`, "", `### ${c.id} — ${c.titleEn}`, "", `**${c.titleTh}**`, "");
      out.push("| Field | Value |", "|---|---|");
      out.push(`| Severity (default) | ${c.severity} |`, `| Priority | ${PRIORITY_TH[c.priority]} |`, `| Automation | ${AUTO_TH[c.automation]}${c.milestone ? ` (${c.milestone})` : ""} |`);
      out.push(`| OWASP Top 10:2025 | ${c.owasp2025.join("<br>") || "—"} |`, `| OWASP Top 10:2021 | ${c.owasp2021.join("<br>") || "—"} |`, `| CWE | ${c.cwe.join(", ") || "—"} |`, `| OWASP WSTG | ${c.wstg.join(", ") || "—"} |`, `| OWASP ASVS 5.0 (chapter) | ${c.asvs5Chapter.join(", ") || "—"} |`, `| CVE | ${c.cve?.join(", ") ?? "—"} |`);
      out.push(`| Seen in sources | ${c.sources.length ? c.sources.map((s) => `${s.src} ×${s.count} (${esc(s.label)}; ${s.severity}${s.status ? `; ${s.status}` : ""})`).join("<br>") : "— (required by NavSentry scope, no source occurrence yet)"} |`, "");
      out.push("**FACT (ข้อเท็จจริง)**", "", c.fact, "");
      out.push("**EVIDENCE (หลักฐานที่ต้องเก็บ)**", "", ...c.evidence.map((e) => `- ${e}`), "");
      out.push("**ACCEPTANCE CRITERIA (เกณฑ์ผ่าน)**", "", ...c.acceptance.map((a) => `- [ ] ${a}`), "");
      out.push("**ตรวจซ้ำบนหน้าเว็บจริง (Web recheck)**", "", ...c.webRecheck.map((a) => `- [ ] ${a}`), "");
      out.push(`**แนวทางแก้ (Fix)** — ${c.fix}`, "", `**⚠️ ผลกระทบต่อผู้ใช้จริง / Regression guard** — ${c.regressionGuard}`, "");
      if (c.caveats?.length) out.push("**Caveats / False positive**", "", ...c.caveats.map((x) => `- ${x}`), "");
      out.push("<details><summary>Prompt: VERIFY (ตรวจสอบ)</summary>", "", "```text", verifyPrompt(c), "```", "", "</details>", "");
      out.push("<details><summary>Prompt: FIX (แก้ไข)</summary>", "", "```text", fixPrompt(c), "```", "", "</details>", "");
      out.push("<details><summary>Prompt: RECHECK (ตรวจซ้ำ)</summary>", "", "```text", recheckPrompt(c), "```", "", "</details>", "");
    }
  }
  return out.join("\n");
}

